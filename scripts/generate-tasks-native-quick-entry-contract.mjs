import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const repositoryRoot = fileURLToPath(new URL('../', import.meta.url));
const sourceURL = new URL('../contracts/tasks-native-quick-entry-v1.json', import.meta.url);
const typeScriptURL = new URL(
  '../src/modules/tasks/domain/taskNativeQuickEntryContract.generated.ts',
  import.meta.url,
);
const edgeFunctionURL = new URL(
  '../supabase/functions/tasks-widget-actions/nativeQuickEntryContract.generated.ts',
  import.meta.url,
);
const swiftURL = new URL(
  '../macos/TasksCompanion/TasksMac/TasksNativeQuickEntryContract.generated.swift',
  import.meta.url,
);
const checkOnly = process.argv.includes('--check');

const source = await readFile(sourceURL, 'utf8');
const contract = JSON.parse(source);
const canonical = `${JSON.stringify(contract, null, 2)}\n`;
const fingerprint = createHash('sha256').update(canonical).digest('hex');

const swiftString = (value) => JSON.stringify(String(value));
const swiftOptionalInt = (value) => value == null ? 'nil' : String(value);
const swiftOptionalField = (value) => value == null ? 'nil' : `.init(rawValue: ${swiftString(value)})`;
const swiftCase = (value) => value.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());

const typeScriptOutput = `// Generated by scripts/generate-tasks-native-quick-entry-contract.mjs. Do not edit.\n`
  + `export const taskNativeQuickEntryContractFingerprint = ${JSON.stringify(fingerprint)} as const;\n`
  + `export const taskNativeQuickEntryContract = ${JSON.stringify(contract, null, 2)} as const;\n`;

const edgeFunctionOutput = `// Generated by scripts/generate-tasks-native-quick-entry-contract.mjs. Do not edit.\n`
  + `export const nativeQuickEntryContractFingerprint = ${JSON.stringify(fingerprint)} as const;\n`
  + `export const nativeQuickEntrySchemaVersion = ${contract.schemaVersion} as const;\n`
  + `export const nativeQuickEntryPayloadSchemaVersion = ${contract.payloadSchemaVersion} as const;\n`
  + `export const nativeQuickEntryCapability = ${JSON.stringify(contract.capability)} as const;\n`
  + `export const nativeQuickEntryMaximumPayloadBytes = ${contract.limits.maximumPayloadBytes} as const;\n`;

const fieldCases = contract.fields
  .map((field) => `        case ${swiftCase(field.id)} = ${swiftString(field.id)}`)
  .join('\n');
const fieldValues = contract.fields
  .map((field) => `        .init(\n`
    + `            id: .${swiftCase(field.id)},\n`
    + `            label: ${swiftString(field.label)},\n`
    + `            kind: ${swiftString(field.kind)},\n`
    + `            presentation: ${swiftString(field.presentation)},\n`
    + `            parentFieldID: ${swiftOptionalField(field.parentFieldId)},\n`
    + `            required: ${field.required},\n`
    + `            maximumCharacters: ${swiftOptionalInt(field.maximumCharacters)}\n`
    + `        )`)
  .join(',\n');
const enumValues = (values) => values
  .map((item) => `        .init(value: ${swiftString(item.value)}, label: ${swiftString(item.label)})`)
  .join(',\n');
const commandValues = contract.commands
  .map((item) => `        .init(\n`
    + `            key: ${swiftString(item.key)},\n`
    + `            command: ${swiftString(item.command)},\n`
    + `            fieldID: .${swiftCase(item.fieldId)}\n`
    + `        )`)
  .join(',\n');
const layoutSectionCases = contract.layoutSections
  .map((section) => `        case ${swiftCase(section.id)} = ${swiftString(section.id)}`)
  .join('\n');
const layoutSectionValues = contract.layoutSections
  .map((section) => `        .init(\n`
    + `            id: .${swiftCase(section.id)},\n`
    + `            fieldIDs: [${section.fieldIds.map((id) => `.${swiftCase(id)}`).join(', ')}]\n`
    + `        )`)
  .join(',\n');

const swiftOutput = `// Generated by scripts/generate-tasks-native-quick-entry-contract.mjs. Do not edit.\n`
  + `import Foundation\n\n`
  + `enum TasksNativeQuickEntryContract {\n`
  + `    static let sourceFingerprint = ${swiftString(fingerprint)}\n`
  + `    static let schemaVersion = ${contract.schemaVersion}\n`
  + `    static let payloadSchemaVersion = ${contract.payloadSchemaVersion}\n`
  + `    static let capability = ${swiftString(contract.capability)}\n\n`
  + `    enum FieldID: String, CaseIterable, Codable {\n${fieldCases}\n    }\n\n`
  + `    enum LayoutSectionID: String, CaseIterable {\n${layoutSectionCases}\n    }\n\n`
  + `    struct Field: Equatable {\n`
  + `        let id: FieldID\n        let label: String\n        let kind: String\n`
  + `        let presentation: String\n        let parentFieldID: FieldID?\n`
  + `        let required: Bool\n        let maximumCharacters: Int?\n    }\n\n`
  + `    struct Option: Equatable { let value: String; let label: String }\n`
  + `    struct Command: Equatable { let key: String; let command: String; let fieldID: FieldID }\n\n`
  + `    struct LayoutSection: Equatable { let id: LayoutSectionID; let fieldIDs: [FieldID] }\n\n`
  + `    static let defaultDestination = ${swiftString(contract.defaults.destination)}\n`
  + `    static let defaultTodaySection = ${swiftString(contract.defaults.todaySection)}\n`
  + `    static let defaultActionability = ${swiftString(contract.defaults.actionability)}\n`
  + `    static let maximumChecklistItems = ${contract.limits.maximumChecklistItems}\n`
  + `    static let maximumPayloadBytes = ${contract.limits.maximumPayloadBytes}\n\n`
  + `    static let fields: [Field] = [\n${fieldValues}\n    ]\n\n`
  + `    static let layoutSections: [LayoutSection] = [\n${layoutSectionValues}\n    ]\n\n`
  + `    static let todaySections: [Option] = [\n${enumValues(contract.todaySections)}\n    ]\n\n`
  + `    static let actionabilities: [Option] = [\n${enumValues(contract.actionabilities)}\n    ]\n\n`
  + `    static let commands: [Command] = [\n${commandValues}\n    ]\n`
  + `}\n`;

async function writeOrCheck(url, expected) {
  if (!checkOnly) {
    await writeFile(url, expected);
    return;
  }
  const current = await readFile(url, 'utf8').catch(() => '');
  if (current !== expected) {
    const relativePath = fileURLToPath(url).replace(`${repositoryRoot}/`, '');
    throw new Error(`${relativePath} is stale; regenerate the native Quick Entry contract`);
  }
}

await Promise.all([
  writeOrCheck(typeScriptURL, typeScriptOutput),
  writeOrCheck(edgeFunctionURL, edgeFunctionOutput),
  writeOrCheck(swiftURL, swiftOutput),
]);
