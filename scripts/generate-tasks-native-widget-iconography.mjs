import { readdir, readFile, mkdir, rm, writeFile } from 'node:fs/promises';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import * as Lucide from 'lucide-react';

const sourceURL = new URL(
  '../contracts/tasks-native-widget-iconography-v1.json',
  import.meta.url,
);
const assetCatalogURL = new URL(
  '../ios/TasksCompanion/Shared/TasksWidgetIcons.xcassets/',
  import.meta.url,
);
const swiftURL = new URL(
  '../ios/TasksCompanion/Shared/TaskWidgetLucideIcon.generated.swift',
  import.meta.url,
);
const checkOnly = process.argv.includes('--check');

const contract = JSON.parse(await readFile(sourceURL, 'utf8'));
const roles = Object.entries(contract.roles);
const uniqueLucideNames = [...new Set(roles.map(([, value]) => value.lucide))].sort();

const assetName = (lucideName) => `TaskWidgetLucide${lucideName}`;
const swiftCase = (value) => value.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());

function renderSVG(lucideName) {
  const component = Lucide[lucideName];
  if (!component) {
    throw new Error(`Unknown Lucide icon: ${lucideName}`);
  }
  const strokeWidth = roles.find(([, value]) => value.lucide === lucideName)?.[1]
    .strokeWidth;
  return `${renderToStaticMarkup(React.createElement(component, { strokeWidth }))
    .replace('stroke="currentColor"', 'stroke="#000000"')
    .replace(/ class="[^"]*"/, '')
    .replace(' aria-hidden="true"', '')}\n`;
}

const rootContents = `${JSON.stringify({
  info: { author: 'xcode', version: 1 },
}, null, 2)}\n`;

function imageSetContents(lucideName) {
  return `${JSON.stringify({
    images: [{ filename: `${lucideName}.svg`, idiom: 'universal' }],
    info: { author: 'xcode', version: 1 },
    properties: {
      'preserves-vector-representation': true,
      'template-rendering-intent': 'template',
    },
  }, null, 2)}\n`;
}

const swiftCases = roles
  .map(([role]) => `    case ${swiftCase(role)}`)
  .join('\n');
const swiftAssetNames = roles
  .map(([role, value]) => `        case .${swiftCase(role)}: "${assetName(value.lucide)}"`)
  .join('\n');
const swiftLucideNames = roles
  .map(([role, value]) => `        case .${swiftCase(role)}: "${value.lucide}"`)
  .join('\n');
const swiftOutput = `// Generated by scripts/generate-tasks-native-widget-iconography.mjs. Do not edit.\n`
  + `import SwiftUI\n\n`
  + `enum TaskWidgetLucideIcon: CaseIterable {\n${swiftCases}\n\n`
  + `    var assetName: String {\n        switch self {\n${swiftAssetNames}\n        }\n    }\n\n`
  + `    var lucideName: String {\n        switch self {\n${swiftLucideNames}\n        }\n    }\n`
  + `}\n\n`
  + `struct TaskWidgetLucideIconView: View {\n`
  + `    let icon: TaskWidgetLucideIcon\n\n`
  + `    var body: some View {\n`
  + `        Image(icon.assetName)\n`
  + `            .resizable()\n`
  + `            .renderingMode(.template)\n`
  + `            .aspectRatio(contentMode: .fit)\n`
  + `            .accessibilityHidden(true)\n`
  + `    }\n`
  + `}\n`;

const expectedFiles = new Map([
  ['Contents.json', rootContents],
  ...uniqueLucideNames.flatMap((lucideName) => [
    [`${assetName(lucideName)}.imageset/Contents.json`, imageSetContents(lucideName)],
    [`${assetName(lucideName)}.imageset/${lucideName}.svg`, renderSVG(lucideName)],
  ]),
]);

async function listRelativeFiles(directoryURL, prefix = '') {
  const entries = await readdir(directoryURL, { withFileTypes: true }).catch(() => []);
  const files = [];
  for (const entry of entries) {
    const relative = `${prefix}${entry.name}`;
    if (entry.isDirectory()) {
      files.push(...await listRelativeFiles(new URL(`${entry.name}/`, directoryURL), `${relative}/`));
    } else {
      files.push(relative);
    }
  }
  return files.sort();
}

async function checkGeneratedOutput() {
  const currentSwift = await readFile(swiftURL, 'utf8').catch(() => '');
  if (currentSwift !== swiftOutput) {
    throw new Error('ios/TasksCompanion/Shared/TaskWidgetLucideIcon.generated.swift is stale');
  }
  const actualFiles = await listRelativeFiles(assetCatalogURL);
  const expectedNames = [...expectedFiles.keys()].sort();
  if (JSON.stringify(actualFiles) !== JSON.stringify(expectedNames)) {
    throw new Error('ios/TasksCompanion/Shared/TasksWidgetIcons.xcassets has stale files');
  }
  for (const [relative, expected] of expectedFiles) {
    const current = await readFile(new URL(relative, assetCatalogURL), 'utf8').catch(() => '');
    if (current !== expected) {
      throw new Error(`ios/TasksCompanion/Shared/TasksWidgetIcons.xcassets/${relative} is stale`);
    }
  }
}

async function generateOutput() {
  await rm(assetCatalogURL, { recursive: true, force: true });
  await mkdir(assetCatalogURL, { recursive: true });
  for (const [relative, output] of expectedFiles) {
    const outputURL = new URL(relative, assetCatalogURL);
    await mkdir(new URL('./', outputURL), { recursive: true });
    await writeFile(outputURL, output);
  }
  await writeFile(swiftURL, swiftOutput);
}

if (checkOnly) {
  await checkGeneratedOutput();
} else {
  await generateOutput();
  process.stdout.write(`Generated ${uniqueLucideNames.length} Lucide widget vector assets.\n`);
}
